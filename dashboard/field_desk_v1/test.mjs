import { composeFieldDesk } from "./composer.mjs";
import snapshot from "./actual_snapshot.json" with { type: "json" };
import assert from "node:assert/strict";
const a=composeFieldDesk(snapshot);
assert.equal(a.rail.length,18);
assert.deepEqual(a.tallies,{gold:3,silver:1,bronze:0});
assert.equal(a.observed_markers.length,0);
assert.equal(a.save_metadata_status,"LABELS_ONLY_NOT_DECODED");
assert.equal(a.replays[0],"010");
const b=composeFieldDesk(snapshot,{source:"PLAYER_OBSERVATION",mapMarkers:["009","013"]});
assert.deepEqual(b.observed_markers,["009","013"]);
const c=composeFieldDesk(snapshot,{source:"PLAYER_OBSERVATION",straussDebtDeposited:true,ledgerVisible:true,leatherToolsPurchased:true});
assert.equal(c.camp.stage,"TOOLS_OBSERVED");
const d=composeFieldDesk(snapshot,{source:"PLAYER_OBSERVATION",johnWagonTaskActive:true});
assert.equal(d.risk.type,"ACTIVE_GOLD_RISK");
assert.equal(d.outings_suppressed,true);
const e=composeFieldDesk(snapshot,{source:"PLAYER_OBSERVATION",ledgerVisible:false,leatherToolsPurchased:true});
assert.equal(e.conflicts.length,1);
assert.throws(()=>composeFieldDesk(snapshot,{source:"AUTO_SAVE_GUESS",mapMarkers:["009"]}));
console.log("Field Desk: 10 source/evidence invariants PASSED; game-state writes 0.");
